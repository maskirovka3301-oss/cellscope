#!/bin/sh
# Regenerate the embedded UI shaders. Requires glslangValidator and the
# SDL_shadercross CLI. The generated ui.*.spv/ui.*.msl and gpu_shaders.h are
# committed so normal builds do not need the shader toolchain.
set -eu
cd "$(dirname "$0")/.."
GLSLANG=${GLSLANG:-glslangValidator}
SHADERCROSS=${SHADERCROSS:-shadercross}
"$GLSLANG" -V --target-env vulkan1.0 -S vert src/shaders/ui.vert.glsl -o src/shaders/ui.vert.spv
"$GLSLANG" -V --target-env vulkan1.0 -S frag src/shaders/ui.frag.glsl -o src/shaders/ui.frag.spv
"$SHADERCROSS" src/shaders/ui.vert.spv -s SPIRV -d MSL -t vertex -e main -o src/shaders/ui.vert.msl
"$SHADERCROSS" src/shaders/ui.frag.spv -s SPIRV -d MSL -t fragment -e main -o src/shaders/ui.frag.msl
"$GLSLANG" -V --target-env vulkan1.0 -S vert src/shaders/anatomy.vert.glsl -o src/shaders/anatomy.vert.spv
"$GLSLANG" -V --target-env vulkan1.0 -S frag src/shaders/anatomy.frag.glsl -o src/shaders/anatomy.frag.spv
"$SHADERCROSS" src/shaders/anatomy.vert.spv -s SPIRV -d MSL -t vertex -e main -o src/shaders/anatomy.vert.msl
"$SHADERCROSS" src/shaders/anatomy.frag.spv -s SPIRV -d MSL -t fragment -e main -o src/shaders/anatomy.frag.msl
python3 - <<'PY'
from pathlib import Path

def cstr(data):
    return '\n'.join('    "' + l.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
                     for l in data.decode().splitlines(True))

def cbytes(data):
    return '\n'.join('    ' + ','.join(str(b) for b in data[i:i + 16]) + ','
                     for i in range(0, len(data), 16))

def emit(prefix, names, header, guard):
    h = [f'#ifndef {guard}', f'#define {guard}', '',
         '/* Generated by scripts/compile-gpu-shaders.sh. Do not edit. */', '']
    for name, stage in names:
        msl = Path(f'src/shaders/{name}.msl').read_bytes()
        spv = Path(f'src/shaders/{name}.spv').read_bytes()
        h += [f'static const char {prefix}_{stage}_MSL[] =', cstr(msl) + ';',
              f'static const unsigned char {prefix}_{stage}_SPV[] = {{', cbytes(spv), '};',
              f'static const unsigned int {prefix}_{stage}_SPV_LEN = {len(spv)};', '']
    h.append('#endif')
    Path(header).write_text('\n'.join(h) + '\n')

emit('UI', [('ui.vert', 'VERT'), ('ui.frag', 'FRAG')],
     'src/gpu_shaders.h', 'CELLSCOPE_GPU_SHADERS_H')
emit('ANATOMY', [('anatomy.vert', 'VERT'), ('anatomy.frag', 'FRAG')],
     'src/anatomy_shaders.h', 'CELLSCOPE_ANATOMY_SHADERS_H')
PY
